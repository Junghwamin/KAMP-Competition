# ── 도우미 ─────────────────────────────────────────────────────────────
def set_text(p: Paragraph, text: str) -> None:
    """첫 run 서식을 유지한 채 문단 텍스트를 바꾼다."""
    runs = p.runs
    assert runs, p.text[:40]
    runs[0].text = text
    for r in runs[1:]:
        r._r.getparent().remove(r._r)


def replace_in(p: Paragraph, old: str, new: str, run_idx: int | None = None) -> None:
    runs = p.runs if run_idx is None else [p.runs[run_idx]]
    hits = [r for r in runs if old in r.text]
    assert len(hits) == 1 and hits[0].text.count(old) == 1, (old[:50], len(hits))
    hits[0].text = hits[0].text.replace(old, new)


def clone_after(anchor_el, template: Paragraph, segments) -> Paragraph:
    """template 문단을 복제해 anchor 뒤에 넣는다. segments: str 또는 run별 텍스트 목록."""
    el = copy.deepcopy(template._p)
    anchor_el.addnext(el)
    p = Paragraph(el, template._parent)
    if isinstance(segments, str):
        set_text(p, segments)
    else:
        runs = p.runs
        assert len(runs) >= len(segments), (len(runs), len(segments))
        for r, s in zip(runs, segments):
            r.text = s
        for r in runs[len(segments):]:
            r._r.getparent().remove(r._r)
    return p


def set_cell(cell, text: str) -> None:
    ps = cell.paragraphs
    for extra in ps[1:]:
        extra._p.getparent().remove(extra._p)
    p = ps[0]
    if p.runs:
        set_text(p, text)
    else:
        p.add_run(text)


def chain(anchor_el, items):
    """(template, segments) 목록을 anchor 뒤에 순서대로 붙인다."""
    last = anchor_el
    out = []
    for tpl, seg in items:
        p = clone_after(last, tpl, seg)
        last = p._p
        out.append(p)
    return out


