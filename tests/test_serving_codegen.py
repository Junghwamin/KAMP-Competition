def _defining_node(tree: ast.Module, name: str) -> ast.stmt | None:
    """모듈 최상위에서 `name` 을 정의하는 문장(def·class·대입)을 찾는다."""
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.name == name:
            return node
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == name for t in node.targets
        ):
            return node
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == name:
            return node
    return None


def _core_tree() -> ast.Module:
    """생성된 `serving/_core.py` 의 AST."""
    return ast.parse(CORE_PATH.read_bytes().decode("utf-8"))


def _code_nb(*sources: str, markdown: tuple[str, ...] = ()) -> nbformat.NotebookNode:
    """코드 셀(과 선택적 마크다운 셀)로 합성 노트북을 만든다."""
    cells = [nbformat.v4.new_markdown_cell(m) for m in markdown]
    cells += [nbformat.v4.new_code_cell(s) for s in sources]
    return nbformat.v4.new_notebook(cells=cells)


