# 9 — 개인정보 스캔 정규식 (s10 은 import 하지 않고 소스에서 추출)
# ══════════════════════════════════════════════════════════════════════
def _privacy_pattern(label: str) -> str:
    """src/s10_package.py 의 `PRIVACY_PATTERNS[label]` 문자열 리터럴을 AST 로 꺼낸다."""
    tree = ast.parse((PROJECT_ROOT / "src" / "s10_package.py").read_text(encoding="utf-8"))
    node = _defining_node(tree, "PRIVACY_PATTERNS")
    assert node is not None and isinstance(node.value, ast.Dict)
    for k, v in zip(node.value.keys, node.value.values):
        if isinstance(k, ast.Constant) and k.value == label:
            return ast.literal_eval(v)
    raise AssertionError(f"PRIVACY_PATTERNS 에 '{label}' 이 없다")


