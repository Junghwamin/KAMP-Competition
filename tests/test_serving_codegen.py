def test_core_top_level_has_only_imports_and_definitions():
    """`_core` 최상위에는 import(numpy·pandas)·정의·대입·docstring 만 있다 — 실행 문장이 없다."""
    tree = _core_tree()
    imported = set()
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            imported |= {a.name for a in node.names}
            continue
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            continue   # 모듈 docstring
        assert isinstance(node, (ast.FunctionDef, ast.Assign, ast.AnnAssign)), (
            f"{node.lineno}행: 최상위 실행 문장 {type(node).__name__}"
        )
    # numpy·pandas + 매니페스트 해시용 표준 라이브러리(hashlib·json)만
    assert imported == {"numpy", "pandas", "hashlib", "json"}


