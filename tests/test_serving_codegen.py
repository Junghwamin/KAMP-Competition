    pat = (_privacy_pattern("Windows 절대경로") if pattern_source == "s10"
           else finalize_notebook.SCAN_PATTERNS["Windows 절대경로"])
    assert re.search(pat, _WIN_PATH)
    assert re.search(pat, _WIN_PATH_ESCAPED)
    assert re.search(pat, "C:+Users") is None
    assert re.search(pat, "C:Users") is None
