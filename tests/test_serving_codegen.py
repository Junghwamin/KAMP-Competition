# 5 — import 부작용 없음
# ══════════════════════════════════════════════════════════════════════
def test_core_import_has_no_side_effects(tmp_path):
    """복사한 `serving._core` 를 별도 프로세스에서 import 해도 작업 폴더에 새 파일이 생기지 않는다."""
    # 메인 트리 outputs/ 는 FULL 실행 중 계속 바뀌므로, `_core.py` 를 tmp 로 복사하고
    # CWD 도 tmp 로 둔 채 import 해 tmp 안의 파일 목록(mtime 포함) 변화로 판정한다.
    # 바이트코드 캐시(__pycache__)는 파이썬 자체의 동작이므로 `-B` 로 끈다.
    pkg = tmp_path / "serving"
    pkg.mkdir()
    (pkg / "__init__.py").write_bytes(b"")
    shutil.copyfile(CORE_PATH, pkg / "_core.py")

    def listing() -> list[tuple[str, int, int]]:
        return sorted(
            (p.relative_to(tmp_path).as_posix(), p.stat().st_mtime_ns, p.stat().st_size)
            for p in tmp_path.rglob("*")
        )

    before = listing()
    env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}
    env.update(PYTHONIOENCODING="utf-8", PYTHONDONTWRITEBYTECODE="1")
    code = (
        "import serving._core as c\n"
        "print(c.__file__)\n"
        "print(','.join(sorted(n for n in vars(c) if not n.startswith('__'))))\n"
    )
    proc = subprocess.run(
        [sys.executable, "-X", "utf8", "-B", "-c", code],
        cwd=tmp_path, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=120,
    )
    assert proc.returncode == 0, proc.stderr[-2000:]
    loaded_from, names = proc.stdout.strip().splitlines()[-2:]
    assert Path(loaded_from).resolve() == (pkg / "_core.py").resolve(), "tmp 사본이 아닌 모듈을 import 했다"
    assert REQUIRED_CORE_NAMES <= set(names.split(","))
    assert listing() == before, "import 가 파일을 만들거나 바꿨다"


